// Refresh public metadata only. Audio stays on NetEase; no login or audio files.
// Run: node tools/sync-playlist.mjs
import { execFileSync } from 'node:child_process';
import { writeFile, mkdir } from 'node:fs/promises';

const playlistId = 583921157;
function getJSON(path, params) {
  const url = new URL(path, 'https://music.163.com');
  url.search = new URLSearchParams(params).toString();
  const response = JSON.parse(execFileSync('curl', [
    '--fail', '--silent', '--show-error', '--location', '--max-time', '30', url.href,
  ], { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 }));
  if (response.code !== 200) throw new Error(`NetEase returned ${response.code}`);
  return response;
}

const { playlist } = getJSON('/api/v6/playlist/detail', { id: playlistId, n: 1000 });
const ids = playlist?.trackIds?.map(track => track.id);
if (!ids?.length || ids.some(id => !Number.isSafeInteger(id) || id <= 0)) {
  throw new Error('No valid public tracks. The existing playlist has not been replaced.');
}
const details = new Map();
for (let start = 0; start < ids.length; start += 50) {
  const { songs } = getJSON('/api/song/detail', { ids: JSON.stringify(ids.slice(start, start + 50)) });
  for (const song of songs || []) details.set(song.id, song);
}
const tracks = ids.map(id => {
  const song = details.get(id);
  if (!song?.name) throw new Error(`Missing metadata for ${id}; keeping the existing playlist.`);
  return { id, name: song.name, artist: song.artists.map(a => a.name).join(' / '), duration: song.duration / 1000 };
});
const data = {
  id: playlistId,
  name: playlist.name,
  url: `https://music.163.com/playlist?id=${playlistId}`,
  cover: playlist.coverImgUrl?.replace(/^http:/, 'https:'),
  updatedAt: new Date().toISOString(),
  tracks,
};
const destination = new URL('../assets/music/playlist.js', import.meta.url);
await mkdir(new URL('../assets/music/', import.meta.url), { recursive: true });
await writeFile(destination, '// Generated by tools/sync-playlist.mjs. Public metadata, no audio.\nwindow.DESKTOP_PLAYLIST = ' +
  JSON.stringify(data, null, 2).replace(/</g, '\\u003c') + ';\n');
console.log(`Updated ${tracks.length} tracks: ${playlist.name}`);
